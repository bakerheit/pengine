constexpr bool valid_start_parts(const StartPart* parts, std::size_t count) {
    for (std::size_t i = 0; i < count; ++i) {
        if (parts[i].name == nullptr || parts[i].width_m <= 0.0f ||
            parts[i].height_m <= 0.0f || parts[i].depth_m <= 0.0f ||
            parts[i].bottom_m < 0.0f) {
            return false;
        }
    }
    return true;
}

