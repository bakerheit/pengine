// The first place the player sees: a small roadside gas station and a
// two-storey courtyard motel. This is authored data rather than renderer code
// so the visible boxes and the solid footprints come from one description.
//
// Positions are local to each site. `bottom_m` is above the Pinatty Row plate,
// which is exactly 12 m high. Keeping the art relative to the plate makes the
// table readable: a 5 m wall says 5, not 17.
using StartFinish = BuildingFinish;
using StartPart = BuildingPiece;

inline constexpr float kStartAreaGroundM = 12.0f;

struct StartSite {
    const char* name = nullptr;
    Vec2 origin{};

    // The downtown grid is six degrees off north. Store the basis rather than
    // asking every caller to repeat trig (which is not constexpr in C++17).
    // Rotation about +Y is:
    //   world.x = origin.x + cos*x + sin*z
    //   world.z = origin.z - sin*x + cos*z
    float cos_yaw = 1.0f;
    float sin_yaw = 0.0f;

    Vec2 lot_centre{};
    float lot_width_m = 1.0f;
    float lot_depth_m = 1.0f;
    float ground_m = kStartAreaGroundM;
    float max_draw_distance_m = 900.0f;
};

